export type TKey = keyof typeof DICT;
const IDX: Record<Lang, 0 | 1 | 2> = { ar: 0, tr: 1, en: 2 };
export const LANGS: { code: Lang; label: string }[] = [
  { code: "ar", label: "العربية" },
  { code: "tr", label: "Türkçe" },
  { code: "en", label: "English" },
];

interface I18nCtx {
  lang: Lang;
  dir: "rtl" | "ltr";
  setLang: (l: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  tx: (text: I18nText | undefined) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

function initialLang(): Lang {
  const saved = localStorage.getItem("souqna-lang");
  return saved === "ar" || saved === "tr" || saved === "en" ? saved : "ar";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const dir = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.setAttribute("lang", lang);
    document.documentElement.setAttribute("dir", dir);
  }, [lang, dir]);

  const setLang = useCallback((l: Lang) => {
    localStorage.setItem("souqna-lang", l);
    setLangState(l);
  }, []);

  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>) => {
      let s: string = DICT[key][IDX[lang]];
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );

  const tx = useCallback(
    (text: I18nText | undefined) => (text ? text[lang] || text.ar || text.en || text.tr : ""),
    [lang],
  );

  const value = useMemo(() => ({ lang, dir, setLang, t, tx }), [lang, dir, setLang, t, tx]) as I18nCtx;
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}

